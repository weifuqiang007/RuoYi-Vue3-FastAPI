-- ---------------------------------------------------------------------------
-- 3. 知识库表（设计方案 §2.1 增列后的形态）
-- ---------------------------------------------------------------------------
CREATE TABLE rag_knowledge_base (
  kb_id        BIGINT PRIMARY KEY,
  kb_name      VARCHAR(100),
  kb_scope     VARCHAR(20) NOT NULL DEFAULT 'personal',  -- public/school/class/personal
  scope_dept_id BIGINT,                                  -- school/class 时的 dept_id
  owner_user_id BIGINT,                                  -- 所有者
  del_flag     CHAR(1) DEFAULT '0'
);

